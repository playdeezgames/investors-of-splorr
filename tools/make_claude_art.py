def cell(art):
    rows = [r for r in art.strip("\n").split("\n")]
    rows += ["." * 16] * (16 - len(rows))
    for r in rows:
        assert len(r) == 16, (len(r), r)
    return rows

root = os.path.join(os.path.dirname(__file__), "..")
img = Image.new("RGBA", (16 * len(SPRITES), 16), (0, 0, 0, 0))
for i, art in enumerate(SPRITES.values()):
    for y, row in enumerate(cell(art)):
        for x, ch in enumerate(row):
            if ch == "#":
                img.putpixel((i * 16 + x, y), (255, 255, 255, 255))
out = os.path.join(root, "assets", "claude", "claude_16x16.png")
img.save(out)
print("wrote", out, list(SPRITES))
